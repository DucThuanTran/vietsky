TRUNCATE MART.FACT_AIR_QUALITY_HOURLY;

INSERT INTO MART.FACT_AIR_QUALITY_HOURLY
(LOCATION_KEY, DATE_KEY, HOUR_VN, TS_UTC, PM2_5, PM10, US_AQI, NITROGEN_DIOXIDE, OZONE)
SELECT L.LOCATION_KEY,
       TO_CHAR(S.TS_UTC AT TIME ZONE 'Asia/Ho_Chi_Minh', 'YYYYMMDD')::INT,
       EXTRACT(HOUR FROM S.TS_UTC AT TIME ZONE 'Asia/Ho_Chi_Minh'),
       S.TS_UTC,
       S.PM2_5,
       S.PM10,
       S.US_AQI,
       S.NITROGEN_DIOXIDE,
       S.OZONE
FROM STG_AIR_QUALITY_HOURLY S
         JOIN MART.DIM_LOCATION L ON S.LOCATION_ID = L.LOCATION_ID;

